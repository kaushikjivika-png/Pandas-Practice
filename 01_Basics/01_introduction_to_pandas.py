# Introduction to Pandas

# Pandas is a Python library used for data manipulation (cleaning,  transforming, and structuring data)
# and data analysis (finding patterns, insights and trends).

# What makes pandas unique?

# It works seamlesly with structured data formats like csv, json and excel.

# Pandas provides two main data structures:

# 1. Series - It is a one-dimensional labelled array that can hold any data type:
#             int, float, str etc.

# 2. DataFrame - It is a two dimensional labelled array data structure, similar to a table in excel or Sql table.

# Example:
# A simple table-like dataset

students = {
    "Name": ["Jivika", "Rahul", "Priya"],
    "Age": [20, 21, 19]
}

print(students)
